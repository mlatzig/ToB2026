/**
 * The large test towers of Phase 6a (spec decision 6), generated deterministically and kept as
 * {@value #FILE_NAME} in the test resources (part of the source repository, not of the release binary). Grid
 * coordinates: x 0..15 west → east, y 0..15 north → south, levels 0..5. The look (palette, ground, sun) is
 * {@code original-000}'s. {@code LargeTestTowersTest} checks the file against this generator; regenerate it with
 * {@code mvn -o test -Dtest=LargeTestTowersTest -Dtob.writeTowers=true}.
 * <ul>
 * <li>{@link #FULL} {@code large-000}: the full 16 × 16 × 6 grid; a floor on level 0, a ring on every level, inner
 * rings, and a chain of five up lifts on the north row from level 0 to level 5 plus a down lift on the south row.</li>
 * <li>{@link #NARROW} {@code large-001}: 16 × 4 cells (rows 6..9) on four levels, for the cameras' unequal sides.</li>
 * <li>{@link #CROWDED} {@code large-002}: 10 × 10 × 5 (cells 3..12), just beyond the 8 × 8 area, with 35 objects.</li>
 * <li>{@link #SOLVABLE} {@code large-003}: a 16 × 16 ring on level 0 and a column on level 1; the grabber grabs one
 * klondike to the north, walks east along the south row, rides the lift up and grabs the second one
 * ({@code LargeSolvableTowerTest}).</li>
 * </ul>
 */
public final class LargeTestTowers {

    public static final String FILE_NAME = "large.json";
    /** The library file, relative to the project root. */
    public static final Path FILE = Path.of("src/test/resources/towers", FILE_NAME);
    public static final String FULL = "large-000";
    public static final String NARROW = "large-001";
    public static final String CROWDED = "large-002";
    public static final String SOLVABLE = "large-003";

    private static final Cell FLOOR = new Cell(BaseType.FLOOR, null);
    private static final int LAST = TowerGrid.WIDTH - 1;

    private LargeTestTowers() {
    }

    /** The library as written to {@link #FILE}. */
    public static TowerLibrary library() {
        return new TowerLibrary("large", "ToB 2026 - Large Test Towers", "generated by LargeTestTowers (Phase 6a)",
                List.of(full(), narrow(), crowded(), solvable()));
    }

    /** The tower with {@code id} from {@link #library()}. */
    public static TowerDefinition tower(String id) {
        return library().towers().stream().filter(t -> t.id().equals(id)).findFirst().orElseThrow();
    }

    static TowerDefinition full() {
        TowerGrid.Builder grid = TowerGrid.builder();
        rectangle(grid, 0, 0, LAST, LAST, 0);
        for (int level = 1; level < TowerGrid.LEVELS; level++) {
            ring(grid, 0, 0, LAST, LAST, level);
        }
        ring(grid, 2, 2, 13, 13, 1);
        ring(grid, 4, 4, 11, 11, 2);
        ring(grid, 6, 6, 9, 9, 3);
        rectangle(grid, 7, 7, 8, 8, 4);
        for (int level = 0; level < TowerGrid.LEVELS - 1; level++) {
            liftUp(grid, 1 + 2 * level, 0, level);
        }
        grid.set(14, LAST, 5, new Cell(BaseType.LIFT_DOWN_START, null));
        grid.set(14, LAST, 4, new Cell(BaseType.LIFT_DOWN_STOP, null));
        grid.set(5, 5, 0, new Cell(BaseType.BOX, null));
        grid.set(10, 5, 0, new Cell(BaseType.BOX, null));
        grid.set(5, 10, 0, new Cell(BaseType.BOX, null));
        grid.set(10, 10, 0, new Cell(BaseType.BOX, null));
        place(grid, 2, 13, 0, ObjectType.ZAP);
        place(grid, 3, 13, 0, ObjectType.PSH);
        place(grid, 4, 13, 0, ObjectType.GRB);
        place(grid, 12, 2, 0, ObjectType.KLD);
        place(grid, 8, 0, 5, ObjectType.KLD);
        place(grid, 7, 7, 0, ObjectType.RZN);
        place(grid, 13, 8, 1, ObjectType.WAT);
        place(grid, 4, 7, 2, ObjectType.BLK);
        place(grid, 15, 8, 3, ObjectType.REL);
        place(grid, 7, 7, 4, ObjectType.BFL);
        place(grid, 0, 8, 5, ObjectType.FZE);
        return tower(FULL, 0, "Large Test: Full 16 x 16 x 6", new Conditions(0, false, 2, 0),
                new Effects(true, true, true, 3, 0, 1), grid.build());
    }

    static TowerDefinition narrow() {
        TowerGrid.Builder grid = TowerGrid.builder();
        rectangle(grid, 0, 6, LAST, 9, 0);
        rectangle(grid, 0, 6, LAST, 6, 1);
        rectangle(grid, 0, 9, LAST, 9, 1);
        rectangle(grid, 0, 6, LAST, 9, 2);
        rectangle(grid, 0, 7, LAST, 7, 3);
        liftUp(grid, 0, 7, 0);
        liftUp(grid, LAST, 6, 1);
        liftUp(grid, 8, 8, 2);
        place(grid, 1, 8, 0, ObjectType.ZAP);
        place(grid, 2, 8, 0, ObjectType.PSH);
        place(grid, 3, 8, 0, ObjectType.GRB);
        place(grid, 14, 7, 3, ObjectType.KLD);
        place(grid, 10, 9, 0, ObjectType.FZW);
        place(grid, 6, 6, 2, ObjectType.HOP);
        return tower(NARROW, 1, "Large Test: Narrow 16 x 4", new Conditions(0, false, 1, 0),
                new Effects(false, false, false, 2, 1, 1), grid.build());
    }

    static TowerDefinition crowded() {
        TowerGrid.Builder grid = TowerGrid.builder();
        for (int level = 0; level < 5; level++) {
            if (level % 2 == 0) {
                rectangle(grid, 3, 3, 12, 12, level);
            } else {
                ring(grid, 3, 3, 12, 12, level);
            }
        }
        liftUp(grid, 3, 3, 0);
        liftUp(grid, 12, 3, 1);
        liftUp(grid, 12, 12, 2);
        liftUp(grid, 3, 12, 3);
        place(grid, 5, 12, 0, ObjectType.ZAP);
        place(grid, 7, 12, 0, ObjectType.PSH);
        place(grid, 9, 12, 0, ObjectType.GRB);
        ObjectType[] lower = {ObjectType.KLD, ObjectType.BLK, ObjectType.REL, ObjectType.KLD, ObjectType.PNE,
                ObjectType.CVN, ObjectType.FCU, ObjectType.KLD, ObjectType.FCD, ObjectType.FRZ, ObjectType.WIP,
                ObjectType.KLD, ObjectType.EXC, ObjectType.BFL, ObjectType.TMB, ObjectType.PRM};
        ObjectType[] upper = {ObjectType.KLD, ObjectType.FZN, ObjectType.FPE, ObjectType.RZN, ObjectType.KLD,
                ObjectType.RPN, ObjectType.WON, ObjectType.WOE, ObjectType.WAT, ObjectType.KLD, ObjectType.HOP,
                ObjectType.LZN, ObjectType.LZE, ObjectType.FZS, ObjectType.FPW, ObjectType.RZN};
        for (int i = 0; i < 16; i++) {
            int x = 4 + 2 * (i % 4);
            int y = 4 + 2 * (i / 4);
            place(grid, x, y, 0, lower[i]);
            place(grid, x, y, 2, upper[i]);
        }
        return tower(CROWDED, 2, "Large Test: Crowded 10 x 10 x 5", new Conditions(0, false, 7, 7),
                new Effects(false, true, false, 1, 2, 1), grid.build());
    }

    static TowerDefinition solvable() {
        TowerGrid.Builder grid = TowerGrid.builder();
        ring(grid, 0, 0, LAST, LAST, 0);
        rectangle(grid, LAST, 0, LAST, LAST - 1, 1);
        liftUp(grid, LAST, LAST, 0);
        place(grid, 0, LAST, 0, ObjectType.GRB);
        place(grid, 0, 0, 0, ObjectType.KLD);
        place(grid, LAST, 0, 1, ObjectType.KLD);
        place(grid, LAST, 0, 0, ObjectType.ZAP);
        place(grid, LAST - 1, 0, 0, ObjectType.PSH);
        return tower(SOLVABLE, 3, "Large Test: Long Walk", new Conditions(0, false, 2, 0),
                new Effects(true, false, false, 3, 0, 1), grid.build());
    }

    private static TowerDefinition tower(String id, int index, String title, Conditions conditions, Effects effects,
            TowerGrid grid) {
        return new TowerDefinition(id, 0, index, title, "ToB 2026 test generator", conditions,
                new Behaviour(true, false, 1), effects, new Moon(0, 0, 8, 28, 2), palette(), new Sounds(0, true, true),
                new Lock(false, ""), grid, Optional.of(new RemakeVisuals(0xFFFFFF, 3, 0x004B4B, 0x006969, 6,
                        0xFFFFFF, false, false, 0, 0xA500A5, 0xE10000)));
    }

    /** {@code original-000}'s palette. */
    private static Palette palette() {
        String[] hex = {"000", "700", "900", "F00", "505", "707", "B0B", "000", "08C", "0B0", "0F0", "BB0", "FF0",
            "777", "BBB", "FFF", "077", "055"};
        List<Rgb12> colours = new ArrayList<>();
        for (String colour : hex) {
            colours.add(Rgb12.parseHex(colour));
        }
        return new Palette(colours);
    }

    private static void rectangle(TowerGrid.Builder grid, int x0, int y0, int x1, int y1, int level) {
        for (int y = y0; y <= y1; y++) {
            for (int x = x0; x <= x1; x++) {
                grid.set(x, y, level, FLOOR);
            }
        }
    }

    private static void ring(TowerGrid.Builder grid, int x0, int y0, int x1, int y1, int level) {
        for (int y = y0; y <= y1; y++) {
            for (int x = x0; x <= x1; x++) {
                if (x == x0 || x == x1 || y == y0 || y == y1) {
                    grid.set(x, y, level, FLOOR);
                }
            }
        }
    }

    /** An up lift from ({@code x}, {@code y}, {@code level}) to the cell above. */
    private static void liftUp(TowerGrid.Builder grid, int x, int y, int level) {
        grid.set(x, y, level, new Cell(BaseType.LIFT_UP_START, null));
        grid.set(x, y, level + 1, new Cell(BaseType.LIFT_UP_STOP, null));
    }

    private static void place(TowerGrid.Builder grid, int x, int y, int level, ObjectType type) {
        grid.set(x, y, level, new Cell(grid.get(x, y, level).base(), type));
    }
}
